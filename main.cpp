#include <string>
#include <vector>

void vector_max() {
    std::vector<int> values;
    values.push_back(11);
    values.push_back(29);
    values.push_back(7);
    int best = values[0];
    for (std::size_t i = 1; i < values.size(); ++i) {
        if (values[i] > best) best = values[i];
    }
    (void)best;
}

void balanced_sum() {
    int left = 1 + 2 + 3;
    int right = 4 + 2;
    bool balanced = (left == right);
    (void)balanced;
}

void digit_count() {
    int n = 1234567;
    int digits = 0;
    while (n > 0) { digits += 1; n /= 10; }
    (void)digits;
}

void digit_product() {
    int n = 2345;
    int product = 1;
    while (n > 0) {
        product *= (n % 10);
        n /= 10;
    }
    (void)product;
}

extern "C" int serene_ember();
extern "C" void sable_boulder();
extern "C" void golden_kite();
extern "C" void cobalt_beacon();

int main() {
    vector_max();
    balanced_sum();
    digit_count();
    digit_product();
    sable_boulder();
    golden_kite();
    cobalt_beacon();
    return serene_ember();
}
